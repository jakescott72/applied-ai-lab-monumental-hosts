/**
 * Generate CSV text representation of the sample dataset for download or re-uploading
 */
export function generateSampleCsvString(): string {
  const headers = [
    'id',
    'name',
    'neighbourhood_cleansed',
    'room_type',
    'bedrooms',
    'bathrooms',
    'accommodates',
    'price',
    'review_scores_rating',
    'number_of_reviews',
    'minimum_nights',
    'availability_365',
  ];

  const rows = SAMPLE_DC_LISTINGS.map((l) => [
    l.id,
    `"${l.name.replace(/"/g, '""')}"`,
    `"${l.neighbourhood}"`,
    `"${l.room_type}"`,
    l.bedrooms,
    l.bathrooms ?? 1,
    l.accommodates,
    `$${l.price.toFixed(2)}`,
    l.review_scores_rating ?? '',
    l.number_of_reviews,
    l.minimum_nights,
    l.availability_365 ?? 135,
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}
